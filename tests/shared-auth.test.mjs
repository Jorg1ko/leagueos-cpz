import assert from 'node:assert/strict';
import {sharedCookie,sharedSession,hashPassword,newSalt} from '../functions/shared-auth.js';
const password='Ejemplo-De-Acceso-CPZ-1234',salt=newSalt();
const hashed=await hashPassword(password,salt);
assert.equal(hashed,await hashPassword(password,salt),'La misma clave produce el mismo hash');
assert.notEqual(hashed,await hashPassword(password+'x',salt),'Las claves diferentes no coinciden');
const secret='administrador-secreto-de-pruebas-largo';
let version=2;
const db={prepare(sql){return {run:async()=>({}),first:async()=>({version})}}};
const env={ADMIN_PASSWORD:secret,LEAGUE_DB:db};
const cookie=(await sharedCookie(secret,version)).split(';')[0];
const makeRequest=c=>new Request('https://example.test/',{headers:{Cookie:c}});
assert.equal(await sharedSession(makeRequest(cookie),env),true,'Cookie correcta permite lectura');
version=3;
assert.equal(await sharedSession(makeRequest(cookie),env),false,'Cambiar contraseña revoca sesiones anteriores');
version=2;
assert.equal(await sharedSession(makeRequest(cookie.replace('1.2.','1.5.')),env),false,'No se acepta una versión manipulada');
assert.equal(await sharedSession(makeRequest(''),env),false,'Sin cookie no hay acceso');
console.log('Acceso compartido: hash, sesión firmada, revocación y rechazo: OK');
